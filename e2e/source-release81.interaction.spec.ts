import { expect, test } from "@playwright/test";
import fs from "node:fs";
import path from "node:path";
import { createHash } from "node:crypto";
import { gunzipSync } from "node:zlib";
import { gotoStable, installDeterminism, seedApprovedSession } from "./support/app";

test.use({ video: "off" });
const digest = (bytes: Buffer) => createHash("sha256").update(bytes).digest("hex");
test("public footer offers the genuine matching application source without subscription or private records", async ({ page }, info) => {
  await installDeterminism(page);
  await gotoStable(page, "/");
  const link = page.getByRole("navigation", { name: "Footer navigation" }).getByRole("link", { name: "Source code", exact: true });
  await expect(link).toHaveAttribute("href", "/source/");
  await link.click();
  await expect(page.getByRole("heading", { name: "EdgeLab source code", exact: true })).toBeVisible();
  const response = await page.request.get("/source/manifest.json");
  expect(response.status()).toBe(200);
  const manifest = await response.json();
  expect(manifest.license).toBe("AGPL-3.0-only");
  const built = JSON.parse(fs.readFileSync(path.resolve("frontend/dist/source/manifest.json"), "utf8"));
  expect(manifest).toEqual(built);
  expect(manifest.files.some((file: any) => file.path === "backend/app/main.py")).toBe(true);
  expect(manifest.files.some((file: any) => file.path === "frontend/src/components/EdgeLabWorkspace.tsx")).toBe(true);
  expect(manifest.files.some((file: any) => /(?:^|\/)(?:\.env|AGENTS\.md|PRODUCT\.md|DESIGN\.md|trade_journal.*\.db|EURUSD_M1\.csv)$/.test(file.path))).toBe(false);
  const event = page.waitForEvent("download");
  await page.getByRole("link", { name: "Download source", exact: true }).click();
  const download = await event;
  expect(download.suggestedFilename()).toBe(manifest.archive.name);
  const filename = await download.path();
  expect(filename).not.toBeNull();
  const bytes = fs.readFileSync(filename!);
  expect(bytes.length).toBe(manifest.archive.size); expect(digest(bytes)).toBe(manifest.archive.sha256);
  expect(bytes).toEqual(fs.readFileSync(path.resolve("frontend/dist/source", manifest.archive.name)));
  expect(gunzipSync(bytes).includes(Buffer.from("SOURCE_MANIFEST.json"))).toBe(true);
  await expect(page.getByRole("link", { name: "Licence", exact: true })).toHaveAttribute("href", "/LICENSE.txt");
  const directory = path.resolve(".artifacts/source-release81"); fs.mkdirSync(directory, { recursive: true });
  await page.screenshot({ path: path.join(directory, info.project.name + "-source-download.png"), fullPage: true });
});
for (const rollout of ["fallback", "enabled"] as const) test(rollout + " application settings prominently offer source without confusing it with paid user-data exports", async ({ page }) => {
  await installDeterminism(page, { rollout });
  await seedApprovedSession(page);
  await gotoStable(page, "/app/settings/global");
  const link = page.getByRole("link", { name: "Application source", exact: true });
  await expect(link).toBeVisible(); await expect(link).toHaveAttribute("href", "/source/");
  await expect(link).toHaveAttribute("target", "_blank");
  const popup = page.waitForEvent("popup"); await link.click();
  const source = await popup; await source.waitForLoadState("domcontentloaded");
  await expect(source.getByRole("heading", { name: "EdgeLab source code", exact: true })).toBeVisible();
  await source.close();
});
