// The VM substitutes transport endpoints only. Worker messages below were
// produced by the actual executor, then reconstructed in the bridge's realm so
// native prototype checks and ArrayBuffer transfer operate as in an iframe.
function forward(wire, start) {
  let receive, worker; const messages = [], posted = [];
  const parent = { postMessage(message, _origin, transfers = []) {
    messages.push(structuredClone(message, { transfer: Array.from(transfers) }));
  } };
  const realm = vm.createContext({ TextEncoder, Blob, parent,
    document: { currentScript: { dataset: { job: nonce, origin: "https://edgelab.example", session: "true" } } },
    URL: { createObjectURL() { return "blob:trusted-worker"; }, revokeObjectURL() {} },
    Worker: class { constructor() { worker = this; } postMessage(command) { posted.push(command); } terminate() {} },
    addEventListener(type, callback) { assert.equal(type, "message"); receive = callback; } });
  vm.runInContext(bridge, realm); assert.equal(messages.pop().type, "ready");
  receive({ source: parent, origin: "https://edgelab.example", data: { nonce, type: "start", workerSource: "trusted-worker", request: start } });
  assert.deepEqual(posted, [start]);
  realm.metadata = JSON.stringify({ ...wire, response: { ...wire.response, buffers: undefined } });
  realm.bytes = JSON.stringify((wire.response.buffers ?? []).map(buffer => Array.from(new Uint8Array(buffer))));
  vm.runInContext('globalThis.payload=JSON.parse(metadata);if(payload.response.encoding==="pine-packed-v1")payload.response.buffers=JSON.parse(bytes).map(values=>new Uint8Array(values).buffer);', realm);
  worker.onmessage({ data: realm.payload });
  const result = messages.at(-1);
  receive({ source: parent, origin: "https://edgelab.example", data: { nonce, type: "stop" } });
  assert.equal(messages.at(-1).type, "stopped");
  return result;
}

